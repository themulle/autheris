    [Fact]
    public void EveryRecordedInput_ResolvesExactlyAsBefore()
    {
        Assert.NotEmpty(Golden);
        var mismatches = new List<string>();
        foreach (var (dialect, input, ok, native, isText) in Golden)
        {
            bool actualOk = CatalogTypeMap.TryResolve(dialect, input, out string actualNative, out bool actualIsText);
            if (ok != actualOk || native != actualNative || isText != actualIsText)
            {
                mismatches.Add($"{dialect} '{input}': {actualOk}/'{actualNative}'/{actualIsText}, expected {ok}/'{native}'/{isText}");
            }
        }

        Assert.Empty(mismatches);
    }

    [Fact]
    public void NonAsciiLookalikeLetters_AreRejected() =>
        Assert.False(CatalogTypeMap.TryResolve(TargetSqlDialect.Sqlite, "int\u212a", out _, out _));

    [Fact]
    public void NullInput_HasNoCast_OnEveryDialect()
    {
        foreach (var dialect in Enum.GetValues<TargetSqlDialect>())
        {
            Assert.False(CatalogTypeMap.TryResolve(dialect, null, out _, out _));
        }
    }

    [Fact]
    public void HostileLongInput_IsRejectedWithoutDependingOnTime()
    {
        string hostile = string.Concat(Enumerable.Repeat("a ", 50_000)) + "!";
        foreach (var dialect in new[] { TargetSqlDialect.SqlServer, TargetSqlDialect.PostgreSql, TargetSqlDialect.Oracle, TargetSqlDialect.DuckDb, TargetSqlDialect.Sqlite })
        {
            Assert.False(CatalogTypeMap.TryResolve(dialect, hostile, out _, out _));
        }
    }
