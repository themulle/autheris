namespace Autheris.Tests.Unit.Dbt;

using System.Threading.Tasks;
using Autheris.Application.Dbt.Services;
using Microsoft.Extensions.Logging.Abstractions;
using Shouldly;
using Xunit;

public sealed class DbtSemanticManifestIngestionTests
{
    private const string SampleSemanticManifestJson = """
    {
      "semantic_models": [
        {
          "name": "orders_source",
          "description": "Core orders dataset",
          "node_relation": {
            "relation_name": "analytics.public.orders"
          },
          "entities": [
            { "name": "order_id", "type": "primary" },
            { "name": "customer_id", "type": "foreign" }
          ],
          "measures": [
            { "name": "order_total", "agg": "sum", "expr": "amount", "description": "Sum of order gross value" },
            { "name": "order_count", "agg": "count", "expr": "1", "description": "Total order count" }
          ],
          "dimensions": [
            { "name": "status", "type": "categorical", "description": "Order status" },
            { "name": "ordered_at", "type": "time", "is_partition": true, "description": "Transaction date" }
          ]
        }
      ],
      "metrics": [
        {
          "name": "gross_revenue",
          "type": "simple",
          "description": "Total gross revenue generated by orders",
          "label": "Gross Revenue",
          "type_params": {
            "measure": "order_total"
          },
          "dimensions": ["status", "ordered_at"],
          "meta": {
            "unit": "EUR",
            "tier": "tier-1"
          }
        },
        {
          "name": "completed_orders",
          "type": "simple",
          "description": "Number of completed orders",
          "label": "Completed Orders",
          "filter": "status = 'completed'",
          "type_params": {
            "measure": "order_count"
          },
          "dimensions": ["ordered_at"],
          "meta": {
            "unit": "count"
          }
        }
      ]
    }
    """;

    [Fact]
    public async Task ParseAndIngestAsync_ValidManifest_PopulatesCatalog()
    {
        var catalog = new InMemorySemanticCatalog();
        var service = new DbtSemanticManifestIngestionService(catalog, NullLogger<DbtSemanticManifestIngestionService>.Instance);

        var manifest = await service.ParseAndIngestAsync(SampleSemanticManifestJson);

        manifest.SemanticModels.Count.ShouldBe(1);
        manifest.Metrics.Count.ShouldBe(2);

        // Verify model
        var model = await catalog.GetSemanticModelAsync("orders_source");
        model.ShouldNotBeNull();
        model.Name.ShouldBe("orders_source");
        model.Entities.Count.ShouldBe(2);
        model.Measures.Count.ShouldBe(2);
        model.Dimensions.Count.ShouldBe(2);
        model.Dimensions.ShouldContain(d => d.Name == "ordered_at" && d.IsPartition);

        // Verify metrics
        var allMetrics = await catalog.ListMetricsAsync();
        allMetrics.Count.ShouldBe(2);

        var revMetric = await catalog.GetMetricAsync("gross_revenue");
        revMetric.ShouldNotBeNull();
        revMetric.Label.ShouldBe("Gross Revenue");
        revMetric.Measures.ShouldContain("order_total");
        revMetric.Meta["unit"].ShouldBe("EUR");

        // Filter by model
        var modelMetrics = await catalog.ListMetricsAsync("orders_source");
        modelMetrics.Count.ShouldBe(2);
    }
}
