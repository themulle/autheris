    [SparkFact]
    public async Task CorrelatedOneToMany_ManyToOne_NullFields_AndMaskLiterals_ExecuteOnSpark()
    {
        if (!spark.IsAvailable) throw new InvalidOperationException("Spark unavailable: " + spark.StartupError);

        var (service, _) = CreateService(new Dictionary<TableIdentifier, ResolvedTableAccess>
        {
            [Orders] = Resolved(OrdersMeta(maskEmail: true), Decision(Orders, maskEmail: true), "acme"),
            [Entitlements] = Resolved(EntitlementsMeta(), Decision(Entitlements), "acme")
        });
        var acmePrincipal = new ClaimsPrincipal(new ClaimsIdentity([new Claim("tenant_id", "acme")], "Bearer"));

        // 1:N correlated (no order on entitlements -> CorrelatedUnindexed) + masked email + NULL email preservation
        var oneToMany = new TreeQueryNode(Orders, ["id", "email"])
        {
            OrderBy = [new TreeOrder("id", Descending: true)],
            Limit = 10,
            Relations = [new TreeRelationNode("entitlements", ["id"], ["orderid"], IsList: true, new TreeQueryNode(Entitlements, ["id"]) { Limit = 5 })]
        };

        using var doc = await service.ExecuteAsync(acmePrincipal, oneToMany, null, "spark-1");
        var root = doc.RootElement;
        root.GetArrayLength().ShouldBe(3); // acme rows: 6, 2, 1
        root[0].GetProperty("id").GetInt32().ShouldBe(6);
        root[0].GetProperty("email").GetString().ShouldBe("${spark.sql.literal}\\***");
        root[0].GetProperty("entitlements").EnumerateArray().Select(e => e.GetProperty("id").GetInt32()).ShouldBe([3]);
        root[1].GetProperty("id").GetInt32().ShouldBe(2);
        root[1].GetProperty("entitlements").GetArrayLength().ShouldBe(0); // orderid 2 belongs to tenant 'other'

        // Verify raw NULL email property is emitted when email is Clear and DB value is NULL (ignoreNullFields = false)
        var (clearService, _) = CreateService(new Dictionary<TableIdentifier, ResolvedTableAccess>
        {
            [Orders] = Resolved(OrdersMeta(), Decision(Orders, maskEmail: false), "acme"),
            [Entitlements] = Resolved(EntitlementsMeta(), Decision(Entitlements), "acme")
        });
        using var clearDoc = await clearService.ExecuteAsync(acmePrincipal, new TreeQueryNode(Orders, ["id", "email"]) { Where = new TreeComparison("id", TreeFilterOperator.Eq, 6) }, null, "spark-null");
        clearDoc.RootElement[0].TryGetProperty("email", out var emailProp).ShouldBeTrue();
        emailProp.ValueKind.ShouldBe(JsonValueKind.Null);

        // N:1 singular object: Entitlement 1 -> Order 1 (present), Entitlement 2 (for 'other') -> Order 2 ('acme', so null)
        var (otherService, _) = CreateService(new Dictionary<TableIdentifier, ResolvedTableAccess>
        {
            [Orders] = Resolved(OrdersMeta(), Decision(Orders), "other"),
            [Entitlements] = Resolved(EntitlementsMeta(), Decision(Entitlements), "other")
        });
        var otherPrincipal = new ClaimsPrincipal(new ClaimsIdentity([new Claim("tenant_id", "other")], "Bearer"));
        var singular = new TreeQueryNode(Entitlements, ["id"])
        {
            Limit = 5,
            Relations = [new TreeRelationNode("order", ["orderid"], ["id"], IsList: false, new TreeQueryNode(Orders, ["id"]))]
        };
        using var otherDoc = await otherService.ExecuteAsync(otherPrincipal, singular, null, "spark-n1-null");
        otherDoc.RootElement[0].GetProperty("order").ValueKind.ShouldBe(JsonValueKind.Null);
    }

    [SparkFact]
    public async Task SetBasedCte_And_BinaryTenantIsolation_ExecuteOnSpark()
    {
        if (!spark.IsAvailable) throw new InvalidOperationException("Spark unavailable: " + spark.StartupError);

        var (service, _) = CreateService(new Dictionary<TableIdentifier, ResolvedTableAccess>
        {
            [Orders] = Resolved(OrdersMeta(), Decision(Orders), "acme"),
            [Entitlements] = Resolved(EntitlementsMeta(), Decision(Entitlements), "acme")
        });
        var acmePrincipal = new ClaimsPrincipal(new ClaimsIdentity([new Claim("tenant_id", "acme")], "Bearer"));

        // Child specifies OrderBy -> triggers SetBased CTE on Databricks
        var tree = new TreeQueryNode(Orders, ["id"])
        {
            OrderBy = [new TreeOrder("id")],
            Limit = 10,
            Relations = [new TreeRelationNode("entitlements", ["id"], ["orderid"], IsList: true, new TreeQueryNode(Entitlements, ["id"]) { OrderBy = [new TreeOrder("id")], Limit = 5 })]
        };
        TreeExecutionReport? report = null;
        using var doc = await service.ExecuteAsync(acmePrincipal, tree, null, "spark-setbased", new CaptureObserver(r => report = r));
        report.ShouldNotBeNull();
        report.Lists.ShouldContain(l => l.Strategy == TreeListStrategy.SetBased);
        doc.RootElement.GetArrayLength().ShouldBe(3);
        doc.RootElement[0].GetProperty("id").GetInt32().ShouldBe(1);
        doc.RootElement[0].GetProperty("entitlements").EnumerateArray().Select(e => e.GetProperty("id").GetInt32()).ShouldBe([1]);
        doc.RootElement[2].GetProperty("id").GetInt32().ShouldBe(6);
        doc.RootElement[2].GetProperty("entitlements").EnumerateArray().Select(e => e.GetProperty("id").GetInt32()).ShouldBe([3]);

        // Collation-proof tenant isolation on orders_ci + LIKE ESCAPE '\\' + EXISTS secured-source policy
        if (spark.CollationAvailable)
        {
            var (ciService, _) = CreateService(new Dictionary<TableIdentifier, ResolvedTableAccess>
            {
                [OrdersCi] = Resolved(OrdersCiMeta(), Decision(OrdersCi), "acme")
            });
            using var ciDoc = await ciService.ExecuteAsync(acmePrincipal, new TreeQueryNode(OrdersCi, ["id"]) { Limit = 10 }, null, "spark-ci");
            ciDoc.RootElement.EnumerateArray().Select(r => r.GetProperty("id").GetInt32()).ShouldBe([1]);
        }

        // Subquery RLS (EXISTS on entitlements) compiled via TreeSecuredSourceBuilder and executed on Spark
        var existsWhere = new BinaryExpression(
            new ColumnReference(new SqlQualifiedName([new SqlIdentifier("e"), new SqlIdentifier("orderid")])),
            BinaryOperator.Equal,
            PolicyParameterNamer.Column($"{RowFilterAliases.Target}.id"));
        var existsPolicy = new PolicyPredicateRowPolicy(
            PolicyPredicate.Create(new ExistsExpression(new SelectStatement(null, new QuerySpecification(false,
                [new ColumnSelectItem(new ColumnReference(new SqlQualifiedName([new SqlIdentifier("e"), new SqlIdentifier("id")])), null)],
                new NamedTableSource(new SqlQualifiedName([new SqlIdentifier("default"), new SqlIdentifier("entitlements")]), new SqlIdentifier("e")),
                existsWhere, null, null), null, null)), new Dictionary<string, PolicyValue>()),
            TargetSqlDialect.Databricks,
            new PolicyPredicateRenderer());
        var (secService, _) = CreateService(new Dictionary<TableIdentifier, ResolvedTableAccess>
        {
            [Orders] = Resolved(OrdersMeta(), Decision(Orders, existsPolicy), "acme")
        });
        using var secDoc = await secService.ExecuteAsync(
            acmePrincipal,
            new TreeQueryNode(Orders, ["id"]) { OrderBy = [new TreeOrder("id")], Where = new TreeComparison("email", TreeFilterOperator.EndsWith, "@acme.example"), Limit = 10 },
            null,
            "spark-sec");
        secDoc.RootElement.EnumerateArray().Select(r => r.GetProperty("id").GetInt32()).ShouldBe([1]);
    }

