    private static TableAccessDecision Decision(TableIdentifier id, IRowPolicy? policy = null, bool maskEmail = false)
    {
        var cols = new Dictionary<string, ColumnAccessLevel>(StringComparer.OrdinalIgnoreCase);
        if (id == Orders) cols["email"] = maskEmail ? ColumnAccessLevel.Mask : ColumnAccessLevel.Clear;
        var decision = TableAccessDecision.Allowed(id, cols, hasUnconstrainedColumnAllow: true);
        return policy == null ? decision : decision.WithAdditionalRowPolicy(policy);
    }

    private (GovernedTreeQueryService Service, TreeSecuredSourceBuilder SecuredBuilder) CreateService(
        Dictionary<TableIdentifier, ResolvedTableAccess> access)
    {
        var options = new GatewayOptions
        {
            DataSources = new SqlDataSourceOptions
            {
                Connections = new Dictionary<string, DataSourceConnectionOptions>(StringComparer.OrdinalIgnoreCase)
                {
                    [Source] = new()
