            }
        };

        var secrets = new DictionarySecretProvider();
        var opts = Options.Create(options);
        var http = new HttpClient(new SparkHttpHandler(HandleStatementAsync)) { BaseAddress = new Uri("https://adb-spark-tree.azuredatabricks.net") };
        var client = new DatabricksStatementExecutionClient(http, opts, secrets);
        var resolver = Substitute.For<ITableAccessResolver>();
        resolver.ResolveTableAccessAsync(Arg.Any<ClaimsPrincipal?>(), Arg.Any<TableIdentifier>(), Arg.Any<IReadOnlyList<string>?>(), Arg.Any<IReadOnlyDictionary<string, string[]>?>(), Arg.Any<CancellationToken>())
            .Returns(ci => access[ci.ArgAt<TableIdentifier>(1)]);

        var factory = new TestConnectionFactory(client, options.DataSources.Connections[Source].Databricks!);

        var catalogEntries = new[]
        {
            new TableCatalogEntry(new TableIdentity("default", "orders"), [new("id", "INT"), new("tenantid", "STRING", "UTF8_BINARY"), new("region", "STRING"), new("status", "STRING"), new("amount", "DECIMAL(18,2)"), new("email", "STRING")], "tenantid", 1),
            new TableCatalogEntry(new TableIdentity("default", "entitlements"), [new("id", "INT"), new("tenantid", "STRING", "UTF8_BINARY"), new("orderid", "INT")], "tenantid", 1),
            new TableCatalogEntry(new TableIdentity("default", "orders_ci"), [new("id", "INT"), new("tenantid", "STRING", "UTF8_LCASE")], "tenantid", 1)
        };
        var catalogProvider = Substitute.For<IGovernedCatalogProvider>();
        catalogProvider.GetCatalogAsync(Arg.Any<GovernedDataSource>(), Arg.Any<IReadOnlyCollection<TableIdentifier>>(), Arg.Any<CancellationToken>())
