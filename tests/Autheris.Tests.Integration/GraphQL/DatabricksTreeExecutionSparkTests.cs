            resolver,
            factory,
            Substitute.For<IAuditLogRepository>(),
            new ColumnMaskingProvider(),
            opts,
            securedSourceBuilder: securedBuilder);
        return (service, securedBuilder);
    }

    private async Task<HttpResponseMessage> HandleStatementAsync(HttpRequestMessage req)
    {
        var body = await req.Content!.ReadAsStringAsync();
        using var doc = JsonDocument.Parse(body);
        var root = doc.RootElement;
        var sql = root.GetProperty("statement").GetString()!;
        var sparkParams = new JsonArray();
        if (root.TryGetProperty("parameters", out var parameters) && parameters.ValueKind == JsonValueKind.Array)
        {
            foreach (var p in parameters.EnumerateArray())
            {
                var type = p.GetProperty("type").GetString()?.ToUpperInvariant() switch
                {
                    "INT" => "int32",
                    "BIGINT" => "int64",
                    "BOOLEAN" => "boolean",
                    "DOUBLE" => "double",
                    "DATE" => "date",
                    "TIMESTAMP" or "TIMESTAMP_NTZ" => "timestamp",
                    var t when t is not null && t.StartsWith("DECIMAL", StringComparison.Ordinal) => "decimal",
                    _ => "string"
                };
                sparkParams.Add(new JsonObject
                {
                    ["name"] = p.GetProperty("name").GetString(),
                    ["type"] = type,
                    ["value"] = p.TryGetProperty("value", out var v) && v.ValueKind != JsonValueKind.Null ? v.GetString() : null
                });
            }
        }

        var resp = await spark.SendAsync(new JsonObject { ["op"] = "query", ["sql"] = sql, ["params"] = sparkParams });
        if (resp?["ok"]?.GetValue<bool>() != true)
        {
            return new HttpResponseMessage(HttpStatusCode.BadRequest)
            {
                Content = new StringContent(JsonSerializer.Serialize(new
                {
                    statement_id = Guid.NewGuid().ToString(),
                    status = new { state = "FAILED", error = new { error_code = "SPARK_SQL_ERROR" } }
                }), Encoding.UTF8, "application/json")
            };
        }

        var rows = resp["rows"]!.AsArray().Select(r => r!.AsArray().Select(c => c?.ToString()).ToArray()).ToList();
        var payload = JsonSerializer.Serialize(new
        {
            statement_id = Guid.NewGuid().ToString(),
            status = new { state = "SUCCEEDED" },
            manifest = new { format = "JSON_ARRAY", schema = new { column_count = 1, columns = new[] { new { name = "res", type_name = "STRING", position = 0 } } } },
            result = new { chunk_index = 0, row_offset = 0, data_array = rows }
        });
        return new HttpResponseMessage(HttpStatusCode.OK) { Content = new StringContent(payload, Encoding.UTF8, "application/json") };
    }

