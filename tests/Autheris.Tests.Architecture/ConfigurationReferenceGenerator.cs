using System;
using System.Collections;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using Autheris.Api.Configuration;
using Autheris.Domain.Options;

namespace Autheris.Tests.Architecture;

/// <summary>
/// WP-SIMPL-06 (SEC-SIMPL-61): Reflects over all options types bound under GatewayConfigurationSchema,
/// resolves XML documentation summaries, masks secrets, and renders a comprehensive configuration reference.
/// Never reads IConfiguration, files outside the repository, or environment variables.
/// </summary>
internal static class ConfigurationReferenceGenerator
{
    private static readonly Regex SecretRegex = new(
        @"(?:^|[a-z])(Password|Secret|ApiKey|Key|Token|ConnectionString|Credential|PrivateKey)$",
        RegexOptions.Compiled);

    private static readonly Dictionary<string, XDocument?> AssemblyXmlDocs = new(StringComparer.OrdinalIgnoreCase);
    private static readonly Dictionary<Type, string> SourceFileCache = new();

    public sealed record OptionRow(
        string Key,
        string Type,
        string Default,
        string Description,
        string SourceFile);

    public static string GenerateMarkdown(IEnumerable<(string Path, Type Type)>? customEntries = null)
    {
        var sections = CollectSections(customEntries);
        var sb = new StringBuilder();
        sb.AppendLine("# Configuration Reference");
        sb.AppendLine();
        sb.AppendLine("Generated by ConfigurationReferenceTests; do not edit.");
        sb.AppendLine();

        foreach (var (sectionName, rows) in sections)
        {
            if (rows.Count == 0)
            {
                continue;
            }

            sb.AppendLine($"## {sectionName}");
            sb.AppendLine();
            sb.AppendLine("| Key | Type | Default | Description | Source file |");
            sb.AppendLine("| :--- | :--- | :--- | :--- | :--- |");

            foreach (var row in rows)
            {
                sb.AppendLine($"| {row.Key} | {row.Type} | {row.Default} | {row.Description} | {row.SourceFile} |");
            }

            sb.AppendLine();
        }

        return sb.ToString().TrimEnd() + "\n";
    }

    public static string GenerateSection(string sectionName, Type type)
    {
        var rows = new List<OptionRow>();
        var visited = new HashSet<Type>();
        var instance = TryCreateInstance(type);
        ReflectType(type, sectionName, instance, rows, visited);

        var sb = new StringBuilder();
        sb.AppendLine($"## {sectionName}");
        sb.AppendLine();
        sb.AppendLine("| Key | Type | Default | Description | Source file |");
        sb.AppendLine("| :--- | :--- | :--- | :--- | :--- |");

        foreach (var row in rows)
        {
            sb.AppendLine($"| {row.Key} | {row.Type} | {row.Default} | {row.Description} | {row.SourceFile} |");
        }

        return sb.ToString().TrimEnd() + "\n";
    }

    public static IReadOnlyList<OptionRow> CollectAllRows()
    {
        return CollectSections(null).SelectMany(s => s.Rows).ToList();
    }

    public static IReadOnlyList<(string Section, IReadOnlyList<OptionRow> Rows)> CollectSections(IEnumerable<(string Path, Type Type)>? customEntries)
    {
        var sections = new SortedDictionary<string, List<OptionRow>>(StringComparer.Ordinal);
        var visited = new HashSet<Type>();

        if (customEntries != null)
        {
            foreach (var (path, type) in customEntries)
            {
                if (!sections.TryGetValue(path, out var list))
                {
                    list = new List<OptionRow>();
                    sections[path] = list;
                }
                var inst = TryCreateInstance(type);
                ReflectType(type, path, inst, list, visited);
            }

            return sections.Select(kvp => (kvp.Key, (IReadOnlyList<OptionRow>)kvp.Value)).ToList();
        }

        // Process Gateway root options
        var rootInstance = TryCreateInstance(typeof(GatewayOptions));
        var gwProps = typeof(GatewayOptions).GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(p => p.GetIndexParameters().Length == 0 && p.CanWrite && p.GetSetMethod(false) != null)
            .OrderBy(p => p.Name, StringComparer.Ordinal);

        foreach (var prop in gwProps)
        {
            var shape = GatewayConfigurationSchema.Classify(prop.PropertyType, out _);
            if (shape == GatewayConfigurationSchema.Shape.Complex)
            {
                var sectionName = "Gateway:" + prop.Name;
                if (!sections.TryGetValue(sectionName, out var list))
                {
                    list = new List<OptionRow>();
                    sections[sectionName] = list;
                }
                var childInstance = rootInstance != null ? prop.GetValue(rootInstance) : null;
                childInstance ??= TryCreateInstance(prop.PropertyType);
                ReflectType(prop.PropertyType, sectionName, childInstance, list, visited);
            }
            else
            {
                const string sectionName = "Gateway";
                if (!sections.TryGetValue(sectionName, out var list))
                {
                    list = new List<OptionRow>();
                    sections[sectionName] = list;
                }
                ReflectProperty(typeof(GatewayOptions), prop, sectionName, rootInstance, list);
            }
        }

        // Process SideBound entries
        foreach (var (path, type) in GatewayConfigurationSchema.SideBound)
        {
            if (!sections.TryGetValue(path, out var list))
            {
                list = new List<OptionRow>();
                sections[path] = list;
            }
            var inst = TryCreateInstance(type);
            ReflectType(type, path, inst, list, visited);
        }

        return sections.Select(kvp => (kvp.Key, (IReadOnlyList<OptionRow>)kvp.Value)).ToList();
    }

    private static void ReflectType(Type type, string currentPath, object? instance, List<OptionRow> rows, HashSet<Type> visited)
    {
        if (!visited.Add(type))
        {
            return;
        }

        try
        {
            var props = type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                .Where(p => p.GetIndexParameters().Length == 0 && p.CanWrite && p.GetSetMethod(false) != null)
                .OrderBy(p => p.Name, StringComparer.Ordinal);

            foreach (var prop in props)
            {
                var propPath = currentPath + ":" + prop.Name;
                var propVal = instance != null ? TryGetValue(prop, instance) : null;

                if (IsSecretLike(prop))
                {
                    if (propVal != null)
                    {
                        if (propVal is string s && s.Length > 0)
                        {
                            throw new InvalidOperationException(
                                $"Secret-like option '{propPath}' has non-empty default value: '{s}'. Defaults for secret-like options are prohibited (SEC-SIMPL-04, SEC-SIMPL-61).");
                        }
                        if (propVal is not string)
                        {
                            throw new InvalidOperationException(
                                $"Secret-like option '{propPath}' has non-null default value of type '{propVal.GetType().Name}'. Defaults for secret-like options are prohibited (SEC-SIMPL-04, SEC-SIMPL-61).");
                        }
                    }

                    AddOrUpdateRow(rows, new OptionRow(
                        propPath,
                        FormatType(prop.PropertyType),
                        "<secret>",
                        GetDescription(prop),
                        FindSourceFile(type)));
                    continue;
                }

                var shape = GatewayConfigurationSchema.Classify(prop.PropertyType, out _);
                if (shape == GatewayConfigurationSchema.Shape.Complex)
                {
                    var childInstance = propVal ?? TryCreateInstance(prop.PropertyType);
                    ReflectType(prop.PropertyType, propPath, childInstance, rows, visited);
                }
                else
                {
                    AddOrUpdateRow(rows, new OptionRow(
                        propPath,
                        FormatType(prop.PropertyType),
                        FormatDefault(propVal, prop.PropertyType),
                        GetDescription(prop),
                        FindSourceFile(type)));
                }
            }
        }
        finally
        {
            visited.Remove(type);
        }
    }

    private static void ReflectProperty(Type declaringType, PropertyInfo prop, string currentPath, object? instance, List<OptionRow> rows)
    {
        var propPath = currentPath + ":" + prop.Name;
        var propVal = instance != null ? TryGetValue(prop, instance) : null;

        if (IsSecretLike(prop.Name))
        {
            if (propVal != null)
            {
                if (propVal is string s && s.Length > 0)
                {
                    throw new InvalidOperationException(
                        $"Secret-like option '{propPath}' has non-empty default value: '{s}'. Defaults for secret-like options are prohibited (SEC-SIMPL-04, SEC-SIMPL-61).");
                }
                if (propVal is not string)
                {
                    throw new InvalidOperationException(
                        $"Secret-like option '{propPath}' has non-null default value of type '{propVal.GetType().Name}'. Defaults for secret-like options are prohibited (SEC-SIMPL-04, SEC-SIMPL-61).");
                }
            }

            AddOrUpdateRow(rows, new OptionRow(
                propPath,
                FormatType(prop.PropertyType),
                "<secret>",
                GetDescription(prop),
                FindSourceFile(declaringType)));
            return;
        }

        AddOrUpdateRow(rows, new OptionRow(
            propPath,
            FormatType(prop.PropertyType),
            FormatDefault(propVal, prop.PropertyType),
            GetDescription(prop),
            FindSourceFile(declaringType)));
    }

    private static void AddOrUpdateRow(List<OptionRow> rows, OptionRow newRow)
    {
        var existingIdx = rows.FindIndex(r => string.Equals(r.Key, newRow.Key, StringComparison.OrdinalIgnoreCase));
        if (existingIdx >= 0)
        {
            if (rows[existingIdx].Description.StartsWith("Specifies the ", StringComparison.Ordinal) &&
                !newRow.Description.StartsWith("Specifies the ", StringComparison.Ordinal))
            {
                rows[existingIdx] = newRow;
            }
        }
        else
        {
            rows.Add(newRow);
        }
    }

    internal static bool IsSecretLike(PropertyInfo prop)
    {
        if (prop.PropertyType == typeof(bool)) return false;
        return IsSecretLike(prop.Name);
    }

    internal static bool IsSecretLike(string name)
    {
        if (name.EndsWith("SensitivityKey", StringComparison.OrdinalIgnoreCase) ||
            name.EndsWith("ProjectKey", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }
        return SecretRegex.IsMatch(name);
    }

    private static object? TryGetValue(PropertyInfo prop, object instance)
    {
        try
        {
            return prop.GetValue(instance);
        }
        catch
        {
            return null;
        }
    }

    private static object? TryCreateInstance(Type type)
    {
        try
        {
            return Activator.CreateInstance(type);
        }
        catch
        {
            return null;
        }
    }

    private static string FormatType(Type type)
    {
        var shape = GatewayConfigurationSchema.Classify(type, out var element);
        if (shape == GatewayConfigurationSchema.Shape.List && element != null)
        {
            return $"list<{FormatTypeName(element)}>";
        }

        if (shape == GatewayConfigurationSchema.Shape.Dictionary && element != null)
        {
            return $"map<string,{FormatTypeName(element)}>";
        }

        if (shape == GatewayConfigurationSchema.Shape.FreeForm)
        {
            return "object";
        }

        return FormatTypeName(type);
    }

    private static string FormatTypeName(Type type)
    {
        var underlying = Nullable.GetUnderlyingType(type);
        if (underlying != null)
        {
            return FormatTypeName(underlying) + "?";
        }

        if (type == typeof(string)) return "string";
        if (type == typeof(int)) return "int";
        if (type == typeof(long)) return "long";
        if (type == typeof(bool)) return "bool";
        if (type == typeof(double)) return "double";
        if (type == typeof(float)) return "float";
        if (type == typeof(decimal)) return "decimal";
        if (type == typeof(TimeSpan)) return "TimeSpan";
        if (type == typeof(DateTime)) return "DateTime";
        if (type == typeof(DateTimeOffset)) return "DateTimeOffset";
        if (type == typeof(Guid)) return "Guid";
        if (type == typeof(Uri)) return "Uri";

        return type.Name;
    }

    private static string FormatDefault(object? val, Type type)
    {
        if (val == null)
        {
            return "null";
        }

        if (val is string s)
        {
            return s.Length == 0 ? "\"\"" : s;
        }

        if (val is bool b)
        {
            return b ? "true" : "false";
        }

        if (val is TimeSpan ts)
        {
            return ts.ToString();
        }

        if (val is IEnumerable enumerable && val is not IDictionary)
        {
            var count = 0;
            var items = new List<string>();
            foreach (var item in enumerable)
            {
                count++;
                if (items.Count < 5)
                {
                    items.Add(item?.ToString() ?? "null");
                }
            }

            if (count == 0) return "[]";
            return "[" + string.Join(", ", items) + (count > 5 ? ", ..." : "") + "]";
        }

        if (val is IDictionary dict)
        {
            return dict.Count == 0 ? "{}" : $"{{{dict.Count} entries}}";
        }

        return val.ToString() ?? "null";
    }

    private static string GetDescription(PropertyInfo prop)
    {
        // 1. Try reading from assembly XML doc
        var xmlDoc = GetOrLoadXmlDoc(prop.DeclaringType?.Assembly);
        if (xmlDoc != null && prop.DeclaringType != null)
        {
            var typeName = prop.DeclaringType.FullName?.Replace('+', '.');
            var memberName = $"P:{typeName}.{prop.Name}";
            var memberElem = xmlDoc.Descendants("member").FirstOrDefault(m => string.Equals(m.Attribute("name")?.Value, memberName, StringComparison.Ordinal));
            if (memberElem != null)
            {
                var summary = memberElem.Element("summary")?.Value;
                if (!string.IsNullOrWhiteSpace(summary))
                {
                    return CleanSummary(summary);
                }
            }
        }

        // 2. Try parsing source file directly
        if (prop.DeclaringType != null)
        {
            var sourceFile = FindSourceFileRaw(prop.DeclaringType);
            if (sourceFile != null && File.Exists(Path.Combine(RepositoryScan.RepoRoot, sourceFile)))
            {
                var text = RepositoryScan.ReadText(sourceFile);
                var summary = ExtractPropertySummaryFromSource(text, prop.Name);
                if (!string.IsNullOrWhiteSpace(summary))
                {
                    return CleanSummary(summary);
                }
            }
        }

        // 3. Fallback clean description
        return $"Specifies the {prop.Name} setting.";
    }

    private static string CleanSummary(string raw)
    {
        // Strip XML tags
        var stripped = Regex.Replace(raw, @"<[^>]+>", " ");
        // Collapse whitespace
        var collapsed = Regex.Replace(stripped, @"\s+", " ").Trim();
        // Escape markdown pipe
        return collapsed.Replace("|", "\\|");
    }

    private static string? ExtractPropertySummaryFromSource(string sourceCode, string propertyName)
    {
        var pattern = $@"(?:\/\/\/\s*<summary>\s*((?:(?!\/\/\/\s*<\/summary>)[\s\S])*?)\s*\/\/\/\s*<\/summary>\s*(?:\[[^\]]+\]\s*)*public\s+[^\n]+\b{Regex.Escape(propertyName)}\b)";
        var match = Regex.Match(sourceCode, pattern);
        if (match.Success)
        {
            var lines = match.Groups[1].Value.Split('\n');
            var cleaned = lines.Select(l => l.Trim().TrimStart('/', ' ')).Where(l => l.Length > 0);
            return string.Join(" ", cleaned);
        }

        return null;
    }

    private static XDocument? GetOrLoadXmlDoc(Assembly? assembly)
    {
        if (assembly == null || string.IsNullOrEmpty(assembly.Location))
        {
            return null;
        }

        var xmlPath = Path.ChangeExtension(assembly.Location, ".xml");
        if (AssemblyXmlDocs.TryGetValue(xmlPath, out var doc))
        {
            return doc;
        }

        if (File.Exists(xmlPath))
        {
            try
            {
                doc = XDocument.Load(xmlPath);
                AssemblyXmlDocs[xmlPath] = doc;
                return doc;
            }
            catch
            {
                AssemblyXmlDocs[xmlPath] = null;
                return null;
            }
        }

        AssemblyXmlDocs[xmlPath] = null;
        return null;
    }

    private static string FindSourceFile(Type type)
    {
        var raw = FindSourceFileRaw(type);
        return raw != null ? $"`{raw}`" : "`src/`";
    }

    private static string? FindSourceFileRaw(Type type)
    {
        if (SourceFileCache.TryGetValue(type, out var cached))
        {
            return cached;
        }

        var typeName = type.IsGenericType ? type.Name.Substring(0, type.Name.IndexOf('`')) : type.Name;
        var pattern = $@"\b(class|struct|record|enum)\s+{Regex.Escape(typeName)}\b";

        foreach (var file in RepositoryScan.ProductionFiles)
        {
            if (Regex.IsMatch(file.Text, pattern))
            {
                var rel = file.RelativePath.Replace('\\', '/');
                SourceFileCache[type] = rel;
                return rel;
            }
        }

        return null;
    }
}
