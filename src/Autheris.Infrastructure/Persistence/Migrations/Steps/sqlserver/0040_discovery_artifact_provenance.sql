-- Discovery artifact provenance, composite key (table_id, provenance), and fail-closed import constraint.

IF COL_LENGTH(N'dbo.CATALOG_DISCOVERY_ARTIFACTS', N'provenance') IS NULL
    ALTER TABLE dbo.CATALOG_DISCOVERY_ARTIFACTS
        ADD provenance NVARCHAR(16) NOT NULL CONSTRAINT DF_CATALOG_DISCOVERY_ARTIFACTS_provenance DEFAULT N'UNKNOWN';

-- batch

DECLARE @pk sysname = (SELECT kc.name FROM sys.key_constraints kc WHERE kc.parent_object_id = OBJECT_ID(N'dbo.CATALOG_DISCOVERY_ARTIFACTS') AND kc.type = N'PK' AND kc.name <> N'PK_CATALOG_DISCOVERY_ARTIFACTS');
DECLARE @sql NVARCHAR(MAX) = N'ALTER TABLE dbo.CATALOG_DISCOVERY_ARTIFACTS DROP CONSTRAINT ' + QUOTENAME(@pk);
IF @pk IS NOT NULL EXEC(@sql);

-- batch

IF OBJECT_ID(N'dbo.PK_CATALOG_DISCOVERY_ARTIFACTS', N'PK') IS NULL
    ALTER TABLE dbo.CATALOG_DISCOVERY_ARTIFACTS
        ADD CONSTRAINT PK_CATALOG_DISCOVERY_ARTIFACTS PRIMARY KEY (table_id, provenance);

-- batch

IF OBJECT_ID(N'dbo.CK_CATALOG_DISCOVERY_ARTIFACTS_IMPORT_NO_STATS', N'C') IS NULL
    ALTER TABLE dbo.CATALOG_DISCOVERY_ARTIFACTS
        ADD CONSTRAINT CK_CATALOG_DISCOVERY_ARTIFACTS_IMPORT_NO_STATS CHECK (provenance <> N'IMPORT' OR statistics_json IS NULL);
