#!/usr/bin/env bash
# G7 scope injection (ARCH-MNT wave 3, WAVE3-SQLGATE-SC-01/SC-02).
#
# Stryker.NET instruments every file of the project and applies `mutate` only as a status filter afterwards, which made the nightly
# mutation run time out. `--apply` prepends `// Stryker disable all` to every src/TrinoSqlEngine/**/*.cs outside the `mutate` globs of
# stryker-config.json, so those mutants are created as Ignored and are never compiled in. The globs are the single source of the scope.
#
# Usage: g7-scope.sh --apply [--shard I/N] [--root DIR]   CI only (CI=true); edits the checkout, so the tree must be clean. Locally: git checkout -- src/TrinoSqlEngine
#        g7-scope.sh --list  [--shard I/N] [--root DIR]   prints the in-scope files (relative to the root), changes nothing.
# --shard I/N (0-based, SC-06): only the files g7-shard.py assigns to shard I stay in scope; the other in-scope files are marked too,
# so that N parallel jobs each mutate a disjoint part of the globs. Without --shard the whole glob set is in scope.
# Fail closed (exit 1): empty scope, a glob that matches no file, unreadable globs, a dirty tree, a marker already in an in-scope file.
set -euo pipefail

MARKER='// Stryker disable all : outside the G7 mutate scope'
mode=""
root="."
shard=""
while [ $# -gt 0 ]; do
  case "$1" in
    --apply|--list) mode="$1" ;;
    --shard) shard="${2:?--shard needs I/N}"; shift ;;
    --root) root="${2:?--root needs a directory}"; shift ;;
    *) echo "g7-scope: unknown argument '$1'" >&2; exit 2 ;;
  esac
  shift
done
[ -n "$mode" ] || { echo "usage: g7-scope.sh --apply|--list [--root DIR]" >&2; exit 2; }

fail() { echo "g7-scope: $*" >&2; exit 1; }

root="$(cd "$root" && pwd)"
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
config="$root/stryker-config.json"
project_dir="src/TrinoSqlEngine"
[ -f "$config" ] || fail "stryker-config.json not found in $root"
[ -d "$root/$project_dir" ] || fail "$project_dir not found in $root"

if [ "$mode" = "--apply" ]; then
  git -C "$root" rev-parse --is-inside-work-tree >/dev/null 2>&1 || fail "not a git checkout"
  [ "${CI:-}" = "true" ] || fail "refusing to edit sources outside CI (set CI=true)"
  [ -z "$(git -C "$root" status --porcelain --untracked-files=all)" ] || fail "the working tree is not clean"
fi

mapfile -t globs < <(jq -er '.["stryker-config"].mutate[]' "$config") || fail "cannot read the mutate globs from stryker-config.json"
[ "${#globs[@]}" -gt 0 ] || fail "no mutate globs configured"

# glob -> anchored ERE: '**/' = any directories, '*' = anything but '/', '.' literal.
glob_regex() {
  local g="$1"
  g="${g//./\\.}"
  g="${g//\*\*\//§DS§}"
  g="${g//\*/[^/]*}"
  g="${g//§DS§/(.*/)?}"
  printf '^%s$' "$g"
}

mapfile -t all_files < <(cd "$root" && find "$project_dir" -name '*.cs' -not -path '*/obj/*' -not -path '*/bin/*' | LC_ALL=C sort)

is_generated() {
  case "$1" in *.g.cs|*.designer.cs|*.Designer.cs|*.generated.cs) return 0 ;; esac
  head -n 5 "$root/$1" | grep -qi '<auto-generated' 
}

in_scope=()
out_scope=()
declare -A matched
for f in "${all_files[@]}"; do
  rel="${f#"$project_dir"/}"
  hit=0
  for g in "${globs[@]}"; do
    if [[ "$rel" =~ $(glob_regex "$g") ]]; then hit=1; matched["$g"]=1; fi
  done
  if [ "$hit" = 1 ]; then in_scope+=("$f"); elif ! is_generated "$f"; then out_scope+=("$f"); fi
done

for g in "${globs[@]}"; do
  [ -n "${matched[$g]:-}" ] || fail "the glob '$g' matches no file"
done
[ "${#in_scope[@]}" -gt 0 ] || fail "the in-scope file set is empty"

if [ -n "$shard" ]; then
  [[ "$shard" =~ ^([0-9]+)/([0-9]+)$ ]] || fail "--shard must look like I/N"
  shard_index="${BASH_REMATCH[1]}"
  shard_count="${BASH_REMATCH[2]}"
  all_list="$(mktemp)"
  printf '%s\n' "${in_scope[@]}" > "$all_list"
  mapfile -t mine < <(python3 -I "$script_dir/g7-shard.py" --in-scope-list "$all_list" --root "$root" --shards "$shard_count" --index "$shard_index" --weights "$script_dir/g7-weights.json") \
    || { rm -f "$all_list"; fail "shard assignment failed"; }
  rm -f "$all_list"
  [ "${#mine[@]}" -gt 0 ] || fail "the shard is empty"
  declare -A keep
  for f in "${mine[@]}"; do keep["$f"]=1; done
  shard_in=()
  for f in "${in_scope[@]}"; do
    if [ -n "${keep[$f]:-}" ]; then shard_in+=("$f"); else out_scope+=("$f"); fi
  done
  in_scope=("${shard_in[@]}")
fi

if [ "$mode" = "--list" ]; then
  printf '%s\n' "${in_scope[@]}"
  exit 0
fi

for f in "${in_scope[@]}"; do
  if grep -q 'Stryker disable' "$root/$f"; then fail "in-scope file '$f' already contains a Stryker marker"; fi
done

for f in "${out_scope[@]}"; do
  # Insert after a UTF-8 BOM, if there is one.
  sed -i "1s|^\(\xEF\xBB\xBF\)\{0,1\}|\1${MARKER}\n|" "$root/$f"
done

# After-apply check: no in-scope file carries a marker; every out-of-scope file starts with it (the BOM aside).
for f in "${in_scope[@]}"; do
  if grep -q 'Stryker disable' "$root/$f"; then fail "in-scope file '$f' received a Stryker marker"; fi
done
for f in "${out_scope[@]}"; do
  head -n 1 "$root/$f" | grep -qF "$MARKER" || fail "out-of-scope file '$f' did not receive the marker"
done

echo "g7-scope: ${shard:+shard $shard: }${#in_scope[@]} files in scope, ${#out_scope[@]} files marked out of scope"
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  printf '### G7 scope\n\nIn scope: %s files, marked out of scope: %s files.\n' "${#in_scope[@]}" "${#out_scope[@]}" >> "$GITHUB_STEP_SUMMARY"
fi
